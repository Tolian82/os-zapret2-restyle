#!/usr/bin/env python3
"""Import-only original-FD9 producer of detached seven-entry Voice operator input.

Consume an already completed ordinary orchestrator_build_release(...,
'native-detached', saved_xml). NEVER build a second generator or activate the
runtime. The original lifecycle owner AND a flock on the exact saved
/config.xml inode are required. A failed/power-cut publication is retained
under its private temporary name; it is NEVER silently overwritten.
"""
from __future__ import annotations

import os
from pathlib import Path
import stat
import tempfile

from voice_cutover_backup import _copy_regular, _private_dir, _sync_dir
from voice_native_file_observer import observe_live_files
from voice_native_forward_runtime import _copy_candidate
from voice_native_recovery_quiescence import _locked_config
from voice_native_saved_release_prepare import (
    SEALED_FILES, qualify_saved_voice_release,
)
from voice_release_stage import file_sha256


FILE_NAMES = ("config.xml", "user-traffic.conf", "tcp-ports.txt", "udp-ports.txt")
DIR_NAMES = ("runtime", "managed", "voice-native-candidate")
PREFIX = ".voice-operator-input-"
EXPECTED_SOURCE = {
    "traffic-user.conf", "tcp-ports.txt", "udp-ports.txt",
    "traffic.conf", "dvtws.args", "managed", "voice-native-candidate",
}


class NativeOperatorInputError(RuntimeError):
    pass


def _copy_private(source: Path, dest: Path) -> None:
    info = os.lstat(source)
    if not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid() or info.st_nlink != 1:
        raise NativeOperatorInputError("foreign or linked operator input file")
    _copy_regular(source, dest, info)
    os.chmod(dest, 0o600)


def stage_native_operator_input(
    *, config_path, staged_release, destination, physical_wan, divert_port,
    config_fd, config_owner, require_lifecycle_owner,
) -> dict:
    """Publish a verified, detached whole-runtime input; NEVER create PREPARED.

    The caller owns build provenance: the release must be the original
    orchestrator build for the very Config inode held here, not caller POST
    bytes. This producer independently requalifies its exact generator proof.
    """
    if not callable(require_lifecycle_owner):
        raise NativeOperatorInputError("missing original FD9 authority")
    config_path = Path(config_path)
    staged_release, destination = Path(staged_release), Path(destination)
    if not (staged_release.is_absolute() and destination.is_absolute()) or (
        config_path == destination or staged_release == destination
        or destination.name != "voice-operator-input"
    ):
        raise NativeOperatorInputError("detached input has unsafe path identity")
    parent = destination.parent
    require_lifecycle_owner()
    _locked_config(config_path, config_fd, config_owner)
    _private_dir(parent)
    if os.path.lexists(destination) or any(
        n.startswith(PREFIX) for n in os.listdir(parent)
    ):
        raise NativeOperatorInputError("prior operator input or interrupted stage exists")
    if staged_release.is_symlink() or not staged_release.is_dir() or (
        not EXPECTED_SOURCE.issubset({p.name for p in staged_release.iterdir()})
    ):
        raise NativeOperatorInputError("normal orchestrator release incomplete")
    native = staged_release / "voice-native-candidate"
    if native.is_symlink() or not native.is_dir() or (
        set(p.name for p in native.iterdir()) != set(SEALED_FILES)
    ):
        raise NativeOperatorInputError("incomplete eight-file native release")

    # The source includes managed IPSET and ordinary Strategies generated by
    # the SAME orchestrator. Snapshot its whole-tree evidence on original lock.
    source_before = observe_live_files(config_path, staged_release)
    source_sha = file_sha256(config_path)
    # Reject stale/foreign generator input before leaving ANY durable
    # operator stage. No failed candidate should unnecessarily block legacy.
    qualify_saved_voice_release(
        release_dir=native, managed_source=staged_release / "managed",
        ordinary_source=staged_release / "traffic-user.conf",
        tcp_ports=staged_release / "tcp-ports.txt",
        udp_ports=staged_release / "udp-ports.txt",
        physical_wan=physical_wan, divert_port=divert_port,
        source_config=config_path, source_runtime=native,
        config_path=config_path,
        active_runtime=Path("/usr/local/etc/zapret2/runtime-v2"),
        config_fd=config_fd, config_owner=config_owner,
        require_lifecycle_owner=require_lifecycle_owner,
    )
    if file_sha256(config_path) != source_sha or (
        observe_live_files(config_path, staged_release) != source_before
    ):
        raise NativeOperatorInputError("source changed during prequalification")
    temp = Path(tempfile.mkdtemp(prefix=PREFIX, dir=parent))
    # Keep every partial stage for explicit review instead of unlinking it on
    # an exception. The parent must be private before mkdir, and is fsynced
    # before returning control to the owner.
    os.chmod(temp, 0o700)
    _sync_dir(parent)
    try:
        _copy_private(config_path, temp / "config.xml")
        _copy_candidate(staged_release, temp / "runtime")
        runtime = temp / "runtime"
        moved = runtime / "voice-native-candidate"
        # This is a same-parent, producer-owned candidate tree. No untrusted
        # arbitrary recursive deletion is needed: move the eight-file release.
        os.rename(moved, temp / "voice-native-candidate")
        os.chmod(temp / "voice-native-candidate", 0o700)

        _copy_candidate(runtime / "managed", temp / "managed")
        os.chmod(temp / "managed", 0o700)
        for origin, dest in (
            ("traffic-user.conf", "user-traffic.conf"),
            ("tcp-ports.txt", "tcp-ports.txt"),
            ("udp-ports.txt", "udp-ports.txt"),
        ):
            _copy_private(runtime / origin, temp / dest)
        # The full single-engine candidate must use native merged traffic
        # AND exactly the generator-produced native argv, never old PoC argv.
        for name in ("traffic.conf", "dvtws.args"):
            target = runtime / name
            original = os.lstat(target)
            if not stat.S_ISREG(original.st_mode) or (
                original.st_uid != os.geteuid() or original.st_nlink != 1
            ):
                raise NativeOperatorInputError("foreign ordinary release file")
            os.unlink(target)
            _copy_private(temp / "voice-native-candidate" / name, target)
            os.chmod(target, stat.S_IMODE(original.st_mode))
        # The operator route expects private source roots. Do not loosen
        # permissions before the future five-domain PREPARED transaction.
        os.chmod(runtime, 0o700)
        _sync_dir(runtime)
        _sync_dir(temp)

        require_lifecycle_owner()
        _locked_config(config_path, config_fd, config_owner)
        if file_sha256(config_path) != source_sha or (
            observe_live_files(config_path, staged_release) != source_before
        ):
            raise NativeOperatorInputError("Config or orchestrator source drifted")
        manifest, proof = qualify_saved_voice_release(
            release_dir=temp / "voice-native-candidate",
            managed_source=temp / "managed",
            ordinary_source=temp / "user-traffic.conf",
            tcp_ports=temp / "tcp-ports.txt", udp_ports=temp / "udp-ports.txt",
            physical_wan=physical_wan, divert_port=divert_port,
            source_config=temp / "config.xml", source_runtime=runtime,
            config_path=config_path, active_runtime=Path("/usr/local/etc/zapret2/runtime-v2"),
            config_fd=config_fd, config_owner=config_owner,
            require_lifecycle_owner=require_lifecycle_owner,
        )
        if not proof["enabled_services"] or not manifest["tables"] or (
            set(os.listdir(temp)) != set(FILE_NAMES + DIR_NAMES)
        ):
            raise NativeOperatorInputError("detached Voice operator input unqualified")
        # No other process can adopt this candidate before the final
        # read-back and atomic same-parent, fsync'd publication.
        require_lifecycle_owner()
        _locked_config(config_path, config_fd, config_owner)
        if os.path.lexists(destination) or file_sha256(config_path) != source_sha or (
            observe_live_files(config_path, staged_release) != source_before
        ):
            raise NativeOperatorInputError("operator source drifted before publication")
        os.rename(temp, destination)
        _sync_dir(parent)
        return {
            "state": "native-voice-detached-operator-input-published",
            "saved_xml_sha256": source_sha,
            "safe_to_enable_voice": False,
            "public_voice_apply": False,
        }
    except BaseException:
        # Retain the whole private partial stage for manual review.
        _sync_dir(parent)
        raise
