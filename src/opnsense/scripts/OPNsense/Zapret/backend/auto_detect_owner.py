def _secure_bytes(path: Path, limit: int, owner_uid: int) -> bytes:
    before = path.lstat()
    if (not stat.S_ISREG(before.st_mode) or before.st_nlink != 1
            or before.st_uid != owner_uid or before.st_mode & 0o022
            or not 0 < before.st_size <= limit):
        raise GenerationRefused("untrusted_protected_artifact")
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        pinned = os.fstat(fd)
        if (pinned.st_dev, pinned.st_ino, pinned.st_size) != (
                before.st_dev, before.st_ino, before.st_size):
            raise GenerationRefused("changed_protected_artifact")
        data = os.read(fd, limit + 1)
        after = os.fstat(fd)
        if len(data) > limit or (pinned.st_dev, pinned.st_ino, pinned.st_size, pinned.st_mtime_ns) != (
                after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns):
            raise GenerationRefused("racing_protected_artifact")
        return data
    finally:
        os.close(fd)


def _pid(path: Path, uid: int) -> int:
    value = _secure_bytes(path, 32, uid).decode("ascii").strip()
    if not re.fullmatch(r"[0-9]{1,10}", value) or int(value) <= 1:
        raise GenerationRefused("invalid_launcher_pid")
    return int(value)


def _run(runner, argv: list[str]) -> str:
    result = runner(argv, capture_output=True, text=True, timeout=5, check=False)
    if (result.returncode != 0 or result.stderr or not result.stdout
            or len(result.stdout) > 131072):
        raise GenerationRefused("native_process_query_unavailable")
    return result.stdout


def _freebsd_argv(pid: int, *, sysctl_call=None) -> list[str]:
    """Read exact FreeBSD KERN_PROC_ARGS vector, not the truncated ps display."""
    if type(pid) is not int or not 1 < pid < (1 << 31):
        raise GenerationRefused("invalid_native_process_pid")
    if sysctl_call is None:
        if not sys.platform.startswith("freebsd"):
            raise GenerationRefused("native_argv_requires_freebsd")
        libc = ctypes.CDLL(None, use_errno=True)
        sysctl_call = libc.sysctl
        sysctl_call.argtypes = (
            ctypes.POINTER(ctypes.c_int), ctypes.c_uint, ctypes.c_void_p,
            ctypes.POINTER(ctypes.c_size_t), ctypes.c_void_p, ctypes.c_size_t)
        sysctl_call.restype = ctypes.c_int
    # <sys/sysctl.h>: CTL_KERN, KERN_PROC, KERN_PROC_ARGS, pid.
    mib = (ctypes.c_int * 4)(1, 14, 7, pid)
    for _ in range(3):
        length = ctypes.c_size_t(0)
        if sysctl_call(mib, 4, None, ctypes.byref(length), None, 0) != 0:
            raise GenerationRefused("native_argv_query_failed")
        if not 1 < length.value <= MAX_ARGS:
            raise GenerationRefused("native_argv_invalid_length")
        buf = ctypes.create_string_buffer(length.value)
        size = ctypes.c_size_t(length.value)
        if sysctl_call(mib, 4, buf, ctypes.byref(size), None, 0) != 0:
            if ctypes.get_errno() == errno.ENOMEM:
                continue
            raise GenerationRefused("native_argv_read_failed")
        if not 1 < size.value <= len(buf):
            raise GenerationRefused("native_argv_changed_length")
        raw = buf.raw[:size.value]
        if not raw.endswith(b"\x00"):
            raise GenerationRefused("native_argv_unterminated")
        parts = raw[:-1].split(b"\x00")
        if not parts or any(not part for part in parts):
            raise GenerationRefused("native_argv_empty_argument")
        try:
            return [part.decode("utf-8") for part in parts]
        except UnicodeDecodeError as exc:
            raise GenerationRefused("native_argv_invalid_encoding") from exc
    raise GenerationRefused("native_argv_unstable")


def _snapshot(runner, pid: int) -> tuple[str, list[str]]:
    lines = _run(runner, ["/bin/ps", "-ww", "-p", str(pid), "-o", "lstart=",
                          "-o", "command="]).strip().splitlines()
    if len(lines) != 1:
        raise GenerationRefused("missing_or_ambiguous_process")
    parts = lines[0].split(maxsplit=5)
    if len(parts) != 6:
        raise GenerationRefused("invalid_process_start")
    return " ".join(parts[:5]), parts[5].split()



def _valid_learning_proposal(raw: bytes, owner: dict, original: bytes,
                             argv: bytes) -> tuple[tuple[int, str, str], ...]:
    """Read-only exact native-order proof for TZ6v4 drafts; NEVER authorizes.

    Unlike the installed schema-2 _valid_map this primitive does not permit
    runtime, FD9 producer access, queue rotation, epoch sealing, or ACK.
    It independently checks the exact executable argv semantics of the
    canonical source-map proposal before the original owner may eventually
    promote a *different*, fully protected active-generation format.
    """
    from auto_detect_origin_map import LEARNING_PROPOSAL
    from auto_detect_owned_sources import KNOWN_HOSTLISTS
    from auto_detect_storage import DEBUG_PATH, ROOT
    from global_exclusions import BASE, GLOBAL_POLICY_TRAILING, visible

    if (not isinstance(raw, bytes) or len(raw) > MAX_MAP or
            not isinstance(original, bytes) or not isinstance(argv, bytes) or
            not 0 < len(original) <= MAX_ARGS or not 0 < len(argv) <= MAX_ARGS or
            not isinstance(owner, dict) or
            not HEX32.fullmatch(str(owner.get("id", ""))) or
            not HEX64.fullmatch(str(owner.get("candidate", "")))):
        raise GenerationRefused("invalid_learning_proposal_input")
    try:
        record = json.loads(raw)
        src_tokens = original.decode("utf-8").split()
        dst_tokens = argv.decode("utf-8").split()
        original_rows = segments(original.decode("utf-8"))
        proposed_rows = segments(argv.decode("utf-8"))
    except (ValueError, TypeError, UnicodeError) as exc:
        raise GenerationRefused("invalid_learning_native_projection") from exc
    expected_keys = {
        "schema", "evidence", "activation_authorized", "generation",
        "owner_operation_id", "owner_candidate_sha256", "mode",
        "original_args_sha256", "final_args_sha256", "profiles",
    }
    if (not isinstance(record, dict) or set(record) != expected_keys or
            type(record["schema"]) is not int or record["schema"] != 3 or
            record["evidence"] != LEARNING_PROPOSAL or
            record["activation_authorized"] is not False or
            record["mode"] != "auto" or
            record["generation"] != owner["id"] or
            record["owner_operation_id"] != owner["id"] or
            record["owner_candidate_sha256"] != owner["candidate"] or
            record["original_args_sha256"] != hashlib.sha256(original).hexdigest() or
            record["final_args_sha256"] != hashlib.sha256(argv).hexdigest()):
        raise GenerationRefused("untrusted_learning_generation")
    profiles = record["profiles"]
    if not isinstance(profiles, list) or not 1 < len(profiles) <= 257:
        raise GenerationRefused("invalid_learning_profile_map")
    fields = {"native_number", "role", "source_profile",
              "source_sha256", "selector", "hostlist", "found_source_id",
              "auto_inbox", "debug_identity", "origin_status"}
    if any(not isinstance(p, dict) or set(p) != fields for p in profiles):
        raise GenerationRefused("invalid_learning_profile_fields")
    ordinary = profiles[:len(original_rows)]
    learning = profiles[len(original_rows):-1]
    last = profiles[-1]
    if (len(profiles) != len(original_rows) + len(learning) + 1 or
            last != {
                "native_number": 0, "role": "excluded",
                "source_profile": f"{owner['id']}:default",
                "source_sha256": None, "selector": None, "hostlist": None,
                "found_source_id": None, "auto_inbox": None,
                "debug_identity": None, "origin_status": "unknown-native-default",
            }):
        raise GenerationRefused("invalid_learning_default_profile")
    numbers = []
    sources = {}
    for ordinal, item in enumerate(ordinary, 1):
        native_number = item["native_number"]
        if (item["role"] not in ("working", "excluded") or
                item["source_profile"] != f"{owner['id']}:{ordinal}" or
                item["auto_inbox"] is not None or
                item["debug_identity"] is not None or
                item["found_source_id"] not in (None, "youtube_found", "user_found") or
                not isinstance(item["origin_status"], str) or
                item["origin_status"] not in ALLOWED or
                (item["role"] == "working") !=
                (item["origin_status"] == "known-hostlist") or
                (native_number is not None and
                 (type(native_number) is not int or native_number <= 0))):
            raise GenerationRefused("unqualified_ordinary_learning_source")
        if native_number is not None:
            numbers.append(native_number)
        sources[item["source_profile"]] = (item, original_rows[ordinal - 1])
    if numbers != list(range(1, len(numbers) + 1)):
        raise GenerationRefused("invalid_ordinary_native_numbering")
    if len(learning) > 255 - len(numbers):
        raise GenerationRefused("learning_native_profile_limit")
    debug_flag = "--hostlist-auto-debug=" + str(DEBUG_PATH)
    if learning:
        if (dst_tokens.count(debug_flag) != 1 or
                len(dst_tokens) < 2 or dst_tokens[1] != debug_flag or
                not src_tokens or not src_tokens[0].startswith("--port=")):
            raise GenerationRefused("unqualified_learning_debug")
    elif argv != original:
        raise GenerationRefused("unwarranted_learning_argv_change")
    if any(t.startswith("--hostlist-auto") for t in src_tokens):
        raise GenerationRefused("original_argv_contains_native_auto")
    if len(proposed_rows) != len(original_rows) + len(learning):
        raise GenerationRefused("learning_argv_profile_count_changed")
    for ordinal, row in enumerate(original_rows):
        planned = list(proposed_rows[ordinal])
        if ordinal == 0 and learning:
            if planned.count(debug_flag) != 1:
                raise GenerationRefused("ordinary_native_debug_placement")
            planned.remove(debug_flag)
        if planned != row:
            raise GenerationRefused("ordinary_first_match_order_changed")

    attested = []
    seen = set()
    for index, item in enumerate(learning):
        native_number = len(numbers) + index + 1
        hostlist = item["hostlist"]
        source = sources.get(item["source_profile"])
        if (item["role"] != "learning" or
                type(item["native_number"]) is not int or
                item["native_number"] != native_number or
                item["origin_status"] != "qualified-source-proposal" or
                not isinstance(hostlist, str) or
                hostlist not in KNOWN_HOSTLISTS or
                item["selector"] != f"<HOSTLIST:{hostlist}>" or
                item["found_source_id"] != f"{hostlist}_found" or
                item["debug_identity"] != str(DEBUG_PATH) or
                source is None):
            raise GenerationRefused("unauthorized_learning_destination")
        original_item, original_row = source
        if (original_item["role"] != "working" or
                original_item["hostlist"] != hostlist or
                original_item["selector"] != item["selector"] or
                original_item["source_sha256"] != item["source_sha256"]):
            raise GenerationRefused("learning_source_identity_mismatch")
        expected_inbox = str(ROOT / f"learning-{owner['id']}-{native_number}.txt")
        if item["auto_inbox"] != expected_inbox or expected_inbox in seen:
            raise GenerationRefused("unqualified_learning_native_inbox")
        seen.add(expected_inbox)
        clone = [token for token in visible(original_row)
                 if token.partition("=")[0] not in BASE]
        # Independently reconstruct only Stage-3's exact GENERATED terminal
        # policy suffix. The producer must never move arbitrary user-authored
        # arguments, drop exclusions, change first-match working profiles, or
        # append native auto arguments *after* required global excludes.
        canonical_suffix = []
        while clone and clone[-1] in GLOBAL_POLICY_TRAILING:
            canonical_suffix.insert(0, clone.pop())
        actual = proposed_rows[len(original_rows) + index]
        # --new is the boundary token and is deliberately not in segments().
        if (not clone or
                actual != clone + [
                    f"--hostlist-auto={expected_inbox}",
                    "--hostlist-auto-retrans-reset=0",
                ] + canonical_suffix or
                sum(token.startswith("--hostlist=") for token in clone) != 1 or
                any(token.startswith("--hostlist-auto") for token in clone)):
            raise GenerationRefused("learning_native_profile_is_not_exact_clone")
        attested.append((native_number, hostlist, expected_inbox))
    if sum(t.startswith("--hostlist-auto=") for t in dst_tokens) != len(learning):
        raise GenerationRefused("unexpected_native_learning_producers")
    if sum(t.startswith("--hostlist-auto-debug=") for t in dst_tokens) != int(bool(learning)):
        raise GenerationRefused("unexpected_native_learning_debug")
    return tuple(attested)



LEARNING_ACTIVE = "ORIGINAL_SHARED_GENERATOR_LEARNING_ACTIVE"


def _valid_learning_active(raw: bytes, owner: dict, source: dict,
                           original: bytes, argv: bytes
                           ) -> tuple[tuple[int, str, str], ...]:
    """Qualify a *hypothetically sealed* active schema3 map, not an owner.

    This is a prerequisite for original FD9 pretraffic. It CANNOT grant
    running process identity, P2c/epoch permission, engine start or ACK.
    A caller must independently verify the exact original shared bundle
    seal, root-owned source/argv/map and inherited FD9 before trusting it.
    """
    from auto_detect_origin_map import (
        AttributionError, LEARNING_PROPOSAL, plan_learning_tier,
    )
    if (not isinstance(raw, bytes) or len(raw) > MAX_MAP or
            not isinstance(source, dict) or not isinstance(owner, dict)):
        raise GenerationRefused("unqualified_learning_active_map")
    try:
        actual = json.loads(raw)
        if (not isinstance(actual, dict) or
                actual.get("evidence") != LEARNING_ACTIVE or
                actual.get("activation_authorized") is not True or
                actual.get("schema") != 3):
            raise GenerationRefused("learning_active_not_explicitly_authorized")
        proposed, projection = plan_learning_tier(
            source, original, owner_id=owner["id"],
            owner_candidate_sha256=owner["candidate"])
        if (not isinstance(argv, bytes) or argv != proposed or
                actual != {**projection, "evidence": LEARNING_ACTIVE,
                           "activation_authorized": True}):
            raise GenerationRefused("learning_active_not_original_projection")
        nonactivating = {**actual, "evidence": LEARNING_PROPOSAL,
                         "activation_authorized": False}
        encoded = json.dumps(
            nonactivating, sort_keys=True, separators=(",", ":")).encode()
        approved = _valid_learning_proposal(encoded, owner, original, argv)
        if not approved:
            raise GenerationRefused("learning_active_no_qualified_profiles")
        return approved
    except (ValueError, TypeError, KeyError, UnicodeError,
            AttributionError) as exc:
        raise GenerationRefused("learning_active_source_or_argv_refused") from exc


def _valid_map(raw: bytes, owner: dict, argv: bytes) -> tuple[dict, tuple]:
    try:
        data = json.loads(raw)
    except (UnicodeError, ValueError, TypeError) as exc:
        raise GenerationRefused("corrupt_generation_map") from exc
    required = {"schema", "generation", "evidence", "owner_operation_id",
                "owner_candidate_sha256", "final_args_sha256", "mode",
                "raw_path", "debug_path", "observer_native_number", "profiles"}
    if (not isinstance(data, dict) or set(data) != required or
            type(data["schema"]) is not int or data["schema"] != 2 or
            data["evidence"] != "ORIGINAL_SHARED_GENERATOR_CAPTURE" or
            data["mode"] != "auto" or
            data["owner_operation_id"] != owner["id"] or
            data["generation"] != owner["id"] or
            data["owner_candidate_sha256"] != owner["candidate"] or
            data["final_args_sha256"] != hashlib.sha256(argv).hexdigest()):
        raise GenerationRefused("stale_or_unauthorized_generation")
    for name in ("raw_path", "debug_path"):
        value = data[name]
        if (not isinstance(value, str) or not value.startswith("/")
                or len(value) > 512 or "\x00" in value or
                any(segment in ("", ".", "..") for segment in value[1:].split("/"))):
            raise GenerationRefused("unsafe_native_observation_path")
    if data["raw_path"] == data["debug_path"]:
        raise GenerationRefused("overlapping_raw_and_debug")
    tokens = argv.decode("utf-8").split()
    for flag, expected in (
        ("--hostlist-auto=", data["raw_path"]),
        ("--hostlist-auto-debug=", data["debug_path"]),
    ):
        matches = [t[len(flag):] for t in tokens if t.startswith(flag)]
        if matches != [expected]:
            raise GenerationRefused("observation_path_differs_from_native_argv")
    # The actual observer must be the trailing, no-action native profile.
    # An earlier action profile would affect first-match behavior; a guessed
    # observer number in metadata is never sufficient evidence.
    rows = segments(argv.decode("utf-8"))
    if not rows:
        raise GenerationRefused("missing_native_observer")
    observer_row = rows[-1]
    if ("--hostlist-auto=" + data["raw_path"] not in observer_row or
            "--hostlist-auto-retrans-reset=0" not in observer_row or
            any(t.startswith(("--lua-desync", "--import", "--ipset=",
                              "--hostlist=", "--payload")) for t in observer_row)):
        raise GenerationRefused("observer_has_action_or_unauthorized_selector")
    profiles = data["profiles"]
    if not isinstance(profiles, list) or not 1 <= len(profiles) <= 256:
        raise GenerationRefused("invalid_native_profile_map")
    seen = set()
    frozen = []
    for row in profiles:
        if not isinstance(row, dict) or set(row) != {"native_number", "status", "hostlist"}:
            raise GenerationRefused("invalid_native_profile_row")
        no, status, hostlist = row["native_number"], row["status"], row["hostlist"]
        if (no is not None and (type(no) is not int or no < 0 or no > 255)
                or status not in ALLOWED or
                hostlist is not None and (
                    not isinstance(hostlist, str) or
                    not re.fullmatch("[a-z][a-z0-9_-]{0,63}", hostlist))
                or status == "known-hostlist" and hostlist is None
                or status != "known-hostlist" and hostlist is not None
                or no in seen):
            raise GenerationRefused("ambiguous_or_invalid_native_profile")
        if no is not None:
            seen.add(no)
        frozen.append((no, status, hostlist))
    observer = data["observer_native_number"]
    if (type(observer) is not int or observer <= 0 or observer > 255
            or frozen.count((observer, "observer", None)) != 1
            or max((n for n in seen if n > 0), default=0) != observer
            or {n for n in seen if n > 0} != set(range(1, observer + 1))):
        raise GenerationRefused("observer_does_not_match_final_native_map")
    if (0, "unknown-native-default", None) not in frozen:
        raise GenerationRefused("missing_native_default")
    return data, tuple(frozen)


def _exact_common_supervisor_argv(argv: list[str], child_pidfile: Path,
                                  monitored_pid: int | None = None) -> bool:
    """Match the original daemon-launched script, including FreeBSD shebang.

    Native daemon -f may expose either the script itself or its exact /bin/sh
    interpreter prefix in ps(1). Never accept a token merely containing
    supervisor_loop.sh, an arbitrary interpreter, or extra callbacks/args.
    """
    if not isinstance(argv, list) or not isinstance(child_pidfile, Path):
        return False
    expected = [MONITOR_EXEC, str(child_pidfile),
                str(Path(MONITOR_EXEC).with_name("zapret_service.sh")),
                CHILD_EXEC]
    candidates = (expected, ["/bin/sh", *expected])
    if type(monitored_pid) is int and monitored_pid > 1:
        candidates += (expected + [str(monitored_pid)],
                       ["/bin/sh", *expected, str(monitored_pid)])
    return argv in candidates


def _attest_core(*, journal: Path, work_root: Path, active: Path,
                 child_pidfile: Path, monitor_pidfile: Path,
                 runner, owner_uid: int,
                 epoch_finalizing_operation: str | None = None,
                 reviewed_operation: str | None = None,
                 pending_found_record: dict | None = None,
                 argv_reader=None,
                 learning_schema3: bool = False) -> GenerationProof | LearningGenerationProof:
    if argv_reader is None:
        argv_reader = _freebsd_argv
    if type(learning_schema3) is not bool or (
            learning_schema3 and reviewed_operation is not None):
        raise GenerationRefused("unsupported_learning_reviewed_owner")
    record = SharedApplyOperation(journal, owner=owner_uid).read()
    if pending_found_record is not None:
        # Only the private, original-FD9/FD4 Found comparison can inspect
        # a running PREPARED predecessor. Never make it a worker/ACK owner.
        if (reviewed_operation is not None or epoch_finalizing_operation is not None or
                not learning_schema3 or type(pending_found_record) is not dict or
                record != pending_found_record or record["phase"] != "prepared" or
                "found" not in record or "manifest" not in record or
                record.get("previous_manifest", {}).get("schema") != 2 or
                type(record.get("previous")) is not dict or
                record["previous"]["id"] == record["detail"]["id"] or
                record["previous"]["candidate"] != record["detail"]["base"]):
            raise GenerationRefused("unqualified_prepared_found_predecessor")
        owner = record["previous"]
    elif reviewed_operation is not None:
        # Only the explicit original-FD9 rescue may inspect a reviewed
        # generation. Minute/ACK must still reject every unfinished journal.
        if (epoch_finalizing_operation is not None or
                not isinstance(reviewed_operation, str) or
                not HEX32.fullmatch(reviewed_operation) or record is None):
            raise GenerationRefused("invalid_reviewed_native_scope")
        detail = SharedApplyOperation(journal, owner=owner_uid).reviewed_native_detail()
        if detail["id"] != reviewed_operation or record["detail"] != detail:
            raise GenerationRefused("foreign_reviewed_native_generation")
        owner = detail
    elif epoch_finalizing_operation is None:
        # Public worker and ACK never trust an unfinished original epoch.
        if record is None or record["phase"] not in TERMINAL:
            raise GenerationRefused("missing_terminal_common_owner")
        owner = committed_owner(record)
    else:
        # Only the FD9-only entry below passes this exact operation identity.
        if (not isinstance(epoch_finalizing_operation, str) or
                not HEX32.fullmatch(epoch_finalizing_operation) or
                record is None or record["phase"] != "epoch-finalizing" or
                record["detail"]["id"] != epoch_finalizing_operation):
            raise GenerationRefused("unqualified_original_epoch_finalization")
        owner = record["detail"]
    if owner is None or not HEX32.fullmatch(owner["id"]) or not HEX64.fullmatch(owner["candidate"]):
        raise GenerationRefused("missing_committed_common_owner")
    work = work_root / owner["id"]
    verify_seal(work, owner=owner_uid)
    plan = json.loads(_secure_bytes(work / "plan.json", 4 * 1024 * 1024, owner_uid))
    if (not isinstance(plan, dict) or plan.get("page") != owner["page"]
            or plan.get("dependencies") != owner["base"]
            or plan.get("changed_fields") != owner["changed_fields"]):
        raise GenerationRefused("candidate_is_not_committed_owner")
    sealed_argv = _secure_bytes(work / "release" / "dvtws.args", MAX_ARGS, owner_uid)
    active_argv = _secure_bytes(active / "dvtws.args", MAX_ARGS, owner_uid)
    if sealed_argv != active_argv:
        raise GenerationRefused("active_runtime_not_same_sealed_argv")
    raw_map = _secure_bytes(work / "release" / MAP_NAME, MAX_MAP, owner_uid)
    active_map = _secure_bytes(active / MAP_NAME, MAX_MAP, owner_uid)
    if raw_map != active_map:
        raise GenerationRefused("active_generation_not_same_sealed_map")
    if learning_schema3:
        from auto_detect_origin_map import ORIGIN_FILE
        original = _secure_bytes(
            work / "release" / "dvtws.original.args", MAX_ARGS, owner_uid)
        source_bytes = _secure_bytes(
            work / "release" / ORIGIN_FILE, MAX_MAP, owner_uid)
        if (_secure_bytes(active / "dvtws.original.args", MAX_ARGS, owner_uid) !=
                original or
                _secure_bytes(active / ORIGIN_FILE, MAX_MAP, owner_uid) !=
                source_bytes):
            raise GenerationRefused("learning_active_original_source_not_same_release")
        learning = _valid_learning_active(
            raw_map, owner, json.loads(source_bytes), original, sealed_argv)
    else:
        mapping, profiles = _valid_map(raw_map, owner, sealed_argv)

    pid, monitor = _pid(child_pidfile, owner_uid), _pid(monitor_pidfile, owner_uid)
    birth, ps_command = _snapshot(runner, pid)
    # Owner FreeBSD ps -ww truncates this genuine argv at 2048 bytes.
    # ps attests birth/executable only; use the kernel vector for equality.
    if not ps_command or ps_command[0] != CHILD_EXEC:
        raise GenerationRefused("running_engine_executable_differs")
    command = argv_reader(pid)
    expected = [CHILD_EXEC] + sealed_argv.decode("utf-8").split() + [
        "--sockarg=0x200", "--user=nobody"]
    if command != expected:
        raise GenerationRefused("running_engine_argv_differs_from_sealed_owner")
    _, monitor_command = _snapshot(runner, monitor)
    if monitor == pid or not _exact_common_supervisor_argv(monitor_command, child_pidfile, pid):
        raise GenerationRefused("missing_common_supervisor")
    census = _run(runner, ["/bin/ps", "-A", "-ww", "-o", "pid=", "-o", "command="])
    actual = []
    for line in census.splitlines():
        row = line.split()
        if len(row) >= 2 and row[1] == CHILD_EXEC:
            if not row[0].isdigit():
                raise GenerationRefused("untrusted_engine_census")
            actual.append(int(row[0]))
    if actual != [pid]:
        raise GenerationRefused("foreign_or_duplicate_engine")
    token = OwnerToken(pid, birth, CHILD_EXEC)
    if not _owner_snapshot(token, runner):
        raise GenerationRefused("engine_birth_or_executable_changed")
    if (_pid(child_pidfile, owner_uid), _pid(monitor_pidfile, owner_uid)) != (pid, monitor):
        raise GenerationRefused("launcher_owner_changed")
    if _snapshot(runner, pid)[0] != birth or argv_reader(pid) != command:
        raise GenerationRefused("engine_changed_during_owner_read")
    if SharedApplyOperation(journal, owner=owner_uid).read() != record:
        raise GenerationRefused("common_owner_changed_during_read")
    if (_secure_bytes(active / "dvtws.args", MAX_ARGS, owner_uid) != sealed_argv or
            _secure_bytes(active / MAP_NAME, MAX_MAP, owner_uid) != raw_map):
        raise GenerationRefused("active_release_changed_during_read")
    if learning_schema3:
        if (_secure_bytes(active / "dvtws.original.args", MAX_ARGS, owner_uid) !=
                original or
                _secure_bytes(active / ORIGIN_FILE, MAX_MAP, owner_uid) !=
                source_bytes or
                _secure_bytes(work / "release" / "dvtws.original.args",
                              MAX_ARGS, owner_uid) != original or
                _secure_bytes(work / "release" / ORIGIN_FILE,
                              MAX_MAP, owner_uid) != source_bytes):
            raise GenerationRefused("learning_source_changed_during_owner_read")
        return LearningGenerationProof(
            token, owner["id"], owner["id"], owner["candidate"],
            hashlib.sha256(sealed_argv).hexdigest(),
            hashlib.sha256(raw_map).hexdigest(), learning)
    return GenerationProof(token, owner["id"], mapping["generation"],
                           mapping["final_args_sha256"], mapping["raw_path"],
                           mapping["debug_path"], mapping["observer_native_number"],
                           profiles)


