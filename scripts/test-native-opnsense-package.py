#!/usr/bin/env python3
"""Offline positive/negative contracts for the native Mk builder."""
import importlib.util
import os
from pathlib import Path
import unittest
from stage2_source_revision import revision_from_makefile
import tempfile
from unittest.mock import patch

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location(
    "native_production", HERE / "native-opnsense-package.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)


class NativeBuilderTests(unittest.TestCase):
    def test_revision_and_exact_target(self):
        self.assertEqual(mod.REVISION, revision_from_makefile())
        self.assertEqual(mod.private.old.REVISION, revision_from_makefile())
        self.assertEqual(mod.provider.mk.REVISION, revision_from_makefile())
        self.assertEqual(mod.validated_policy()["supported_platforms"][0]["freebsd_pkg_abi"], "FreeBSD:15:amd64")

    def test_staged_bytecode_removed_without_touching_tracked_source(self):
        with tempfile.TemporaryDirectory() as scratch:
            plugin = Path(scratch)
            directory = plugin / "src/opnsense/scripts/OPNsense/Zapret/backend"
            directory.mkdir(parents=True)
            tracked = directory / "owner.py"
            tracked.write_text("print('source')\n")
            cache = directory / "__pycache__"
            cache.mkdir()
            generated = cache / "owner.cpython-313.pyc"
            generated.write_bytes(b"untracked generated bytecode")
            relative = "opnsense/scripts/OPNsense/Zapret/backend/owner.py"
            witness = mod.scrub_staged_source(plugin, {relative})
            self.assertEqual(witness["tracked_source_files"], 1)
            self.assertEqual(witness["discarded_staged_bytecode_files"], 1)
            self.assertFalse(witness["other_untracked_source_accepted"])
            self.assertEqual(tracked.read_text(), "print('source')\n")
            self.assertFalse(cache.exists())

    def test_untracked_foreign_file_refused_before_bytecode_cleanup(self):
        with tempfile.TemporaryDirectory() as scratch:
            plugin = Path(scratch)
            directory = plugin / "src/opnsense"
            directory.mkdir(parents=True)
            trusted = directory / "keep.sh"
            trusted.write_text("#!/bin/sh\n")
            cache = directory / "__pycache__"
            cache.mkdir()
            generated = cache / "keep.cpython-313.pyc"
            generated.write_bytes(b"generated")
            foreign = directory / "foreign.lua"
            foreign.write_text("do-not-package")
            with self.assertRaisesRegex(
                    mod.Refusal, "NATIVE_UNTRACKED_STAGED_SOURCE_FORBIDDEN"):
                mod.scrub_staged_source(plugin, {"opnsense/keep.sh"})
            self.assertEqual(foreign.read_text(), "do-not-package")
            self.assertTrue(generated.is_file())

    def test_tracked_source_git_inventory_rejects_dirty_or_duplicate(self):
        with patch.object(mod, "command", side_effect=[
                b"", b"src/opnsense/foo.py\0src/etc/bar.sh\0"]) as calls:
            self.assertEqual(mod.tracked_source_paths(),
                             {"opnsense/foo.py", "etc/bar.sh"})
            self.assertEqual(calls.call_count, 2)
        with patch.object(mod, "command", return_value=b" M src/opnsense/foo.py"):
            with self.assertRaisesRegex(mod.Refusal, "WORKTREE_DIRTY"):
                mod.tracked_source_paths()
        with patch.object(mod, "command", side_effect=[
                b"", b"src/opnsense/foo.py\0src/opnsense/foo.py\0"]):
            with self.assertRaisesRegex(mod.Refusal, "DUPLICATE"):
                mod.tracked_source_paths()

    def test_missing_optin_refused(self):
        with patch.dict(os.environ, {"ZAPRET2_NATIVE_BUILD_CI": "",
                                      "GITHUB_ACTIONS": "true",
                                      "ZAPRET2_STAGE0_DISPOSABLE_OFFICIAL_MK": "1"}):
            with self.assertRaisesRegex(mod.Refusal, "NOT_OPTED_IN"):
                mod.gate()

    def test_unpinned_source_refused(self):
        with patch.dict(os.environ, {"ZAPRET2_NATIVE_PROJECT_SHA": "not-a-sha"}):
            with self.assertRaisesRegex(mod.Refusal, "EXACT_PROJECT_SHA"):
                mod.git_head()

    def test_mk_accepts_derived_python_and_real_dependencies(self):
        vars = {"PLUGIN_PKGNAME":mod.NAME, "PLUGIN_PKGVERSION":mod.VERSION + "_" + mod.REVISION,
                "PLUGIN_ABI":"26.7", "PLUGIN_HASH":"f"*40,
                "PLUGIN_WWW":mod.PROJECT_URL, "PLUGIN_PYTHON":"313",
                "PLUGIN_DEPENDS":"python313 gmake pkgconf luajit git jq ca_root_nss",
                "PLUGIN_DEVEL":""}
        installed = {n:{} for n in vars["PLUGIN_DEPENDS"].split()}
        with patch.object(mod.private.old, "mkvar",
                          side_effect=lambda p,s,k:vars[k]):
            self.assertEqual(mod.native_make_variables(
                Path("/tmp"), "f"*40, {"native_plugin_python":"313"},installed,
                mod.validated_policy()["supported_platforms"][0]),
                vars)

    def test_mk_refuses_unsafe_dependency_mismatch(self):
        vars = {"PLUGIN_PKGNAME":mod.NAME, "PLUGIN_PKGVERSION":mod.VERSION + "_" + mod.REVISION,
                "PLUGIN_ABI":"26.7", "PLUGIN_HASH":"f"*40,
                "PLUGIN_WWW":mod.PROJECT_URL, "PLUGIN_PYTHON":"313",
                "PLUGIN_DEPENDS":"python313 gmake", "PLUGIN_DEVEL":""}
        with patch.object(mod.private.old, "mkvar",
                          side_effect=lambda p,s,k:vars[k]):
            with self.assertRaisesRegex(mod.Refusal,"VARS_OR_REAL_DEPS_MISMATCH"):
                mod.native_make_variables(Path("/tmp"), "f"*40,
                                          {"native_plugin_python":"313"},
                                          {"python313":{}, "git":{}},
                                          mod.validated_policy()["supported_platforms"][0])

    def test_archive_verification_requires_exact_manual_hooks_and_modes(self):
        source = (HERE / "native-opnsense-package.py").read_text()
        for snippet in ('src.replace(b"%", b"%25")[:-1]',
                        '["-rwxr-xr-x"]',
                        '"NATIVE_ARCHIVE_PRIVATE_ELF_SHA_CHANGED"',
                        'len(name_to_source) == len(files) - 1'):
            self.assertIn(snippet, source)
        self.assertEqual(set(mod.HOOKS.values()),
                         {"pre-install","post-install","pre-deinstall","post-deinstall"})

    def test_signed_source_and_elf_pin_refuses_drift(self):
        lock = {"selection": "pinned", "abi": "FreeBSD:15:amd64",
                "version": "2.2.2", "source_pkg_sha256": "a" * 64,
                "elf_sha256": "b" * 64, "chrome_profile": "chrome145"}
        observed = {"latest_version_diagnostic": "2.2.2",
                    "signed_freebsd_latest_package_sha256": "a" * 64,
                    "private_binary_sha256": "b" * 64,
                    "profile": "chrome145"}
        platform = {"freebsd_pkg_abi": "FreeBSD:15:amd64"}
        self.assertTrue(mod.verified_private_source(lock, observed, platform))
        for field, wrong, refusal in (
                ("latest_version_diagnostic", "2.2.3", "VERSION_MISMATCH"),
                ("signed_freebsd_latest_package_sha256", "c" * 64,
                 "SOURCE_PACKAGE_SHA256_MISMATCH"),
                ("private_binary_sha256", "d" * 64, "ELF_SHA256_MISMATCH"),
                ("profile", "chrome146", "CHROME_PROFILE_MISMATCH")):
            with self.subTest(field=field):
                changed = dict(observed, **{field: wrong})
                with self.assertRaisesRegex(mod.Refusal, refusal):
                    mod.verified_private_source(lock, changed, platform)
        with self.assertRaisesRegex(mod.Refusal, "TARGET_ABI_MISMATCH"):
            mod.verified_private_source(
                lock, observed, {"freebsd_pkg_abi": "FreeBSD:16:amd64"})
        with patch.dict(os.environ, {"ZAPRET2_NATIVE_RELEASE_CANDIDATE": "1"}):
            with self.assertRaisesRegex(mod.Refusal, "RELEASE_REQUIRES_EXACT_PIN"):
                mod.verified_private_source(
                    dict(lock, selection="exploratory"), observed, platform)

    def test_single_official_native_build_and_dist(self):
        source = (HERE / "native-opnsense-package.py").read_text()
        for snippet in ('private.old.clone_official(Path(scratch))',
                        'private.prepare_private(plugin, Path(scratch))',
                        'command(["make", "-C", str(plugin)',
                        'verify_native_package(pkg, plugin, sha, installed, bundle,',
                        'shutil.copyfile(pkg, dest)'):
            self.assertIn(snippet, source)
        for forbidden in ("pkg-static create", "dep_origin()", "chmod("):
            self.assertNotIn(forbidden, source)

    def test_real_signed_catalog_providers_before_make(self):
        source = (HERE / "native-opnsense-package.py").read_text()
        for snippet in ("private.old.guest_gate()", '"pkg", "config", "ABI"',
                        '"pkg", "rquery", "-r", "OPNsense"',
                        'provider.parse_catalog(raw)',
                        'provider.resolve(catalog',
                        'provider.installed_python_crosscheck'):
            self.assertIn(snippet, source)

    def test_native_build_does_not_claim_install_or_release(self):
        source = (HERE / "native-opnsense-package.py").read_text()
        for snippet in ('"actual_product_pkg_installed": False',
                        '"publication_approved": False',
                        '"stage0_closed": False', '"stage1_admitted": False'):
            self.assertIn(snippet, source)
        self.assertIn("native-product-installed-acceptance.json",
                      (HERE.parent / ".github/workflows/release.yml").read_text())

    def test_old_manual_builder_removed_completely(self):
        wrapper = (HERE / "build-pkg.sh").read_text()
        self.assertIn("exec /usr/local/bin/python3", wrapper)
        self.assertIn("ZAPRET2_NATIVE_BUILD_CI", wrapper)
        for forbidden in ("pkg-static create", "dep_origin()", "jq -n",
                          "cp -R src/opnsense", "find "):
            self.assertNotIn(forbidden, wrapper)

    def test_native_python_is_derived_not_hardcoded(self):
        make = (HERE.parent / "Makefile").read_text()
        self.assertIn("python" + chr(36) + "{PLUGIN_PYTHON}", make)
        self.assertNotIn("PLUGIN_DEPENDS=     python313", make)
        self.assertEqual(len(mod.EXPECTED_ROLES), 7)


if __name__ == "__main__":
    unittest.main()
