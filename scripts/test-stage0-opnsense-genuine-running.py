#!/usr/bin/env python3
"""Offline guards for genuinely owned OPNsense Start/Status/Stop acceptance."""
import importlib.util
import os
from pathlib import Path
import tempfile
import unittest
from unittest import mock
import xml.etree.ElementTree as ET

HERE=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('s54',HERE/'stage0-opnsense-genuine-running.py')
m=importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)


class TestGenuineRunning(unittest.TestCase):
    def test_optin_missing_rejected_before_loading_guest(self):
        with mock.patch.dict(os.environ,{m.OPTIN:'0'}),\
             mock.patch.object(m,'module') as module:
            with self.assertRaisesRegex(m.Refusal,'OPTIN'):
                m.qualify_guest()
            module.assert_not_called()

    def test_safe_loopback_port(self):
        self.assertGreater(m.PORT, 49151)
        self.assertEqual(m.RULE,19000)

    def test_test_model_is_enabled_just_for_vm(self):
        root=ET.Element('opnsense')
        z=m.insert_test_model(root)
        self.assertEqual(z.findtext('./OPNsense/Zapret/general/enabled'),'1')
        self.assertEqual(z.findtext('./OPNsense/Zapret/general/waninterface'),'lo0')
        self.assertEqual(z.findtext('./OPNsense/Zapret/general/divertport'),'989')

    def test_test_model_uses_single_loopback_port(self):
        root=m.insert_test_model(ET.Element('opnsense'))
        self.assertEqual(root.findtext('./OPNsense/Zapret/general/ports'),str(m.PORT))
        strategy=root.findtext('./OPNsense/Zapret/strategy/trafficargs')
        self.assertIn('--filter-tcp='+str(m.PORT),strategy)

    def test_original_generated_provenance_refuses_unowned_content(self):
        with tempfile.TemporaryDirectory() as d:
            path=Path(d)/'zapret.conf'
            path.write_bytes(b'foreign data')
            with mock.patch.object(m,'GENERATED',path):
                with self.assertRaises(m.Refusal):
                    m.original_generated()

    def test_original_generated_provenance_accepts_exact_header(self):
        with tempfile.TemporaryDirectory() as d:
            path=Path(d)/'zapret.conf'
            path.write_bytes(b'# Auto-generated by OPNsense os-zapret2 plugin\n')
            with mock.patch.object(m,'GENERATED',path):
                self.assertEqual(m.original_generated()[0],path.read_bytes())
                self.assertEqual(m.original_generated()[2][0],path.lstat().st_uid)

    def test_empty_installed_template_hostlists_saved(self):
        with tempfile.TemporaryDirectory() as d:
            root=Path(d)
            (root/'hostlist.txt').write_bytes(b'\n')
            (root/'hostlist-exclude.txt').write_bytes(b'')
            with mock.patch.object(m,'RUNTIME',root):
                saved=m.original_template_hostlists()
                self.assertEqual(len(saved),2)
                self.assertEqual(saved[root/'hostlist.txt'][0],b'\n')

    def test_nonempty_installed_template_hostlist_is_foreign(self):
        with tempfile.TemporaryDirectory() as d:
            root=Path(d)
            (root/'hostlist.txt').write_text('foreign.example')
            (root/'hostlist-exclude.txt').write_bytes(b'')
            with mock.patch.object(m,'RUNTIME',root):
                with self.assertRaisesRegex(m.Refusal,'NONEMPTY'):
                    m.original_template_hostlists()

    def fake_pinned_source_and_target(self, root):
        source=root/'upstream'
        target=root/'runtime'
        (source/'binaries/my').mkdir(parents=True)
        engine=source/'binaries/my/dvtws2'
        engine.write_bytes(b'actual binary fixture');engine.chmod(0o755)
        (source/'lua').mkdir()
        for name in ('zapret-lib.lua','zapret-antidpi.lua','zapret-auto.lua'):
            (source/'lua'/name).write_bytes(b'-- fixture')
        (source/'files/fake').mkdir(parents=True)
        (source/'files/fake/example.bin').write_bytes(b'fixture')
        target.mkdir()
        for name in ('zapret.conf','hostlist.txt','hostlist-exclude.txt'):
            (target/name).write_bytes(b'')
        return source,target

    def test_pinned_source_fake_directory_is_copied(self):
        with tempfile.TemporaryDirectory() as d:
            source,target=self.fake_pinned_source_and_target(Path(d))
            with mock.patch.object(m,'RUNTIME',target),mock.patch.object(m,'ENGINE',target/'binaries/my/dvtws2'):
                digest=m.stage_engine(source)
            self.assertEqual(len(digest),64)
            self.assertEqual((target/'files/fake/example.bin').read_bytes(),b'fixture')

    def test_missing_pinned_source_fake_directory_refused(self):
        with tempfile.TemporaryDirectory() as d:
            source,target=self.fake_pinned_source_and_target(Path(d))
            import shutil
            shutil.rmtree(source/'files/fake')
            with mock.patch.object(m,'RUNTIME',target),mock.patch.object(m,'ENGINE',target/'binaries/my/dvtws2'):
                with self.assertRaisesRegex(m.Refusal,'GENUINE_UPSTREAM_FAKE_BLOB_DIRECTORY_MISSING'):
                    m.stage_engine(source)

    def test_test_model_voice_absent(self):
        root=m.insert_test_model(ET.Element('opnsense'))
        self.assertIsNone(root.find('./OPNsense/Zapret/voice'))

    def test_original_config_refuses_existing_model(self):
        with tempfile.TemporaryDirectory() as d:
            xml=Path(d)/'conf.xml'
            xml.write_text('<opnsense><OPNsense><Zapret/></OPNsense></opnsense>')
            with mock.patch.object(m,'CONFIG',xml):
                with self.assertRaisesRegex(m.Refusal,'FOREIGN_OR_EXISTING'):
                    m.original_config()

    def test_existing_engine_path_refused(self):
        with tempfile.TemporaryDirectory() as d:
            runtime=Path(d)
            bin=runtime/'engine';bin.write_text('foreign')
            with mock.patch.object(m,'ENGINE',bin):
                self.assertTrue(bin.exists())

    def test_original_config_model_refuses_duplicate(self):
        root=ET.fromstring('<opnsense><OPNsense><Zapret/></OPNsense></opnsense>')
        self.assertIsNotNone(root.find('./OPNsense/Zapret'))

    def test_stop_requires_exact_state(self):
        self.assertEqual(m.PORT,65431)
        self.assertEqual(m.OPTIN,'ZAPRET2_STAGE0_DISPOSABLE_RUNNING_TEST')

    def test_no_package_transaction_claim(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn("'actual_package_upgrade_tested':False",source)
        self.assertIn("'stage0_closed':False",source)
        self.assertIn("'full_lifecycle_acceptance_passed':False",source)

    def test_original_config_keeps_existing_owner_metadata(self):
        with tempfile.TemporaryDirectory() as d:
            path=Path(d)/'config.xml'
            path.write_text('<opnsense/>')
            with mock.patch.object(m,'CONFIG',path):
                original, mode, uid, gid, tree = m.original_config()
                self.assertEqual(uid,path.lstat().st_uid)
                self.assertEqual(gid,path.lstat().st_gid)
                self.assertEqual(original,b'<opnsense/>')

    def test_write_config_chown_target_owner(self):
        with tempfile.TemporaryDirectory() as d:
            path=Path(d)/'config.xml'
            with mock.patch.object(m.os,'chown') as chown:
                m.write_config(b'<opnsense/>',0o640,path,(789,789))
                chown.assert_called_once()
            self.assertEqual(path.read_bytes(),b'<opnsense/>')
            self.assertEqual(path.stat().st_mode & 0o777,0o640)

    def test_temp_runtime_traversal_restored_contract(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn("runtime_initial_mode = stat.S_IMODE(runtime_info.st_mode)",source)
        self.assertIn("RUNTIME.chmod(0o755)",source)
        self.assertIn("RUNTIME.chmod(runtime_initial_mode)",source)
        self.assertIn("ORIGINAL_RUNTIME_DIRECTORY_MODE_NOT_RESTORED",source)

    def test_config_write_not_follow_symlink(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn('stat.S_ISREG(info.st_mode)',source)
        self.assertIn('os.replace(name, target)',source)

    def test_foreign_ipfw_unsafe_unload_refusal_contract(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn("guard.only_default(ipfw.stdout)",source)
        self.assertIn("'POST_STOP_FOREIGN_OR_REMAINING_IPFW_RULES'",source)
        self.assertNotIn("command('/sbin/kldunload'",source)

    def test_residual_process_matches_dvtws_and_supervisor(self):
        lines = ('12 /usr/local/etc/zapret2/binaries/my/dvtws2 --port=989\n'
                 '13 /usr/local/opnsense/scripts/OPNsense/Zapret/backend/supervisor_loop.sh\n'
                 '14 /usr/sbin/daemon -f harmless\n')
        self.assertEqual(len(m.residual_processes(
            lines, ('/dvtws2', '/supervisor_loop.sh', '/zapret_service.sh'))), 2)

    def test_residual_process_refuses_wrong_similar_process(self):
        lines = '1 python scripts/stage0-opnsense-genuine-running.py\n'
        self.assertEqual(m.residual_processes(
            lines, ('/dvtws2','/supervisor_loop.sh','/zapret_service.sh')), [])

    def test_exact_native_supervisor_parent_leak_is_negative(self):
        line=('77448     1 daemon: /usr/local/opnsense/scripts/OPNsense/'
              'Zapret/supervisor_loop.sh[77846] (daemon)')
        result=m.classify_post_stop_residuals([line])
        self.assertEqual(result['outcome'],
                         'HISTORICAL_STOP_LEFT_DAEMONIZED_SUPERVISOR_PARENT')
        self.assertEqual(result['orphan_pid'],77448)

    def test_supervisor_parent_multiple_owners_fail_closed(self):
        line=('77448     1 daemon: /usr/local/opnsense/scripts/OPNsense/'
              'Zapret/supervisor_loop.sh[77846] (daemon)')
        with self.assertRaisesRegex(m.Refusal,'MULTIPLE_OR_FOREIGN'):
            m.classify_post_stop_residuals([line,line])

    def test_unknown_supervisor_process_is_not_clean(self):
        line='782 1 /bin/sh /usr/local/opnsense/scripts/OPNsense/Zapret/supervisor_loop.sh'
        with self.assertRaisesRegex(m.Refusal,'UNRECOGNIZED'):
            m.classify_post_stop_residuals([line])

    def test_no_orphans_explicitly_separate_from_orphan_negative(self):
        outcome=m.classify_post_stop_residuals([])
        self.assertEqual(outcome['outcome'],'NO_OWNED_PROCESSES_AFTER_STOP')
        self.assertIsNone(outcome['orphan_pid'])

    def test_orphan_does_not_grant_pkg_authorization(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn("'native_pkg_replacement_safe_after_stop':False",source)
        self.assertIn("'historical_supervisor_parent_leak_reproduced':not stop_clean",source)
        self.assertIn("inspector.check_process_census(census)",source)

    def test_residual_guard_not_skipped(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn('inspector.check_process_census(census)',source)
        self.assertIn('POST_STOP_POSSIBLE_ZAPRET_PROCESS_PRESENT',source)
        self.assertIn("'-o', 'pid=', '-o', 'ppid='",source)

    def test_no_fake_kernel_cold_after_original_stop(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn("'original_cold_after_stop':False",source)
        self.assertIn("'kernel_modules_remain_loaded':True",source)
        self.assertIn("'no_owned_ipfw_rules_after_stop':True",source)
        self.assertIn('inspector.check_process_census(census)',source)
        self.assertNotIn('stop_and_restore_kernel',source)

    def test_original_fd9_protected(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn("status(service,'start')",source)
        self.assertIn("status(service,'stop')",source)
        self.assertNotIn("LIFECYCLE_LOCK_FILE=str(",source)

    def test_upstream_is_pinned(self):
        source=(HERE/'stage0-opnsense-genuine-running.py').read_text()
        self.assertIn("upstream = module('stage0-opnsense-upstream-engine-build.py')",source)


if __name__=='__main__':
    unittest.main()
