HERE = Path(__file__).resolve().parent
CONFIG = Path('/conf/config.xml')
RUNTIME = Path('/usr/local/etc/zapret2')
ENGINE = RUNTIME / 'binaries/my/dvtws2'
GENERATED = RUNTIME / 'zapret.conf'
PID = Path('/var/run/dvtws2.pid')
RULE = 19000
PORT = 65431
OPTIN = 'ZAPRET2_STAGE0_DISPOSABLE_RUNNING_TEST'


class Refusal(Exception):
    pass


def need(ok, reason):
    if not ok:
        raise Refusal(reason)


def module(name):
    spec = importlib.util.spec_from_file_location(name.replace('-', '_').replace('.', '_'),
                                                   HERE / name)
    obj = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(obj)
    return obj


def command(*args, timeout=75):
    try:
        return subprocess.run(args, capture_output=True, text=True,
                              timeout=timeout, check=False)
    except (OSError, subprocess.SubprocessError):
        raise Refusal('COMMAND_UNAVAILABLE_OR_TIMEOUT:' + args[0]) from None


def status(service, action):
    result = command(service, action, timeout=120)
    return (result.returncode, result.stdout.strip(), result.stderr.strip())


def qualify_guest():
    need(os.getenv(OPTIN) == '1' and os.geteuid() == 0 and
         os.uname().sysname == 'FreeBSD' and os.uname().machine == 'amd64',
         'DISPOSABLE_RUNNING_EXPLICIT_OPTIN_AND_FREEBSD_ROOT_REQUIRED')
    guest = module('stage0-opnsense-guest-readonly.py')
    need(guest.evaluate(guest.observe()).get('status') ==
         'PASS_ISOLATED_OPNSENSE_26_7_GUEST_IDENTITY',
         'TARGET_NOT_QUALIFIED_DISPOSABLE_OPNSENSE')
    need(command('/sbin/ifconfig', 'lo0').returncode == 0,
         'MISSING_SAFE_LOOPBACK_INTERFACE')


def original_config():
    info = CONFIG.lstat()
    need(stat.S_ISREG(info.st_mode) and not CONFIG.is_symlink() and info.st_nlink == 1,
         'CONFIG_NOT_OWNED_REGULAR_FILE:mode=' + oct(info.st_mode) +
         ':uid=' + str(info.st_uid) + ':nlink=' + str(info.st_nlink) +
         ':target=' + (os.readlink(CONFIG) if CONFIG.is_symlink() else 'none'))
    data = CONFIG.read_bytes()
    root = ET.fromstring(data)
    need(root.find('./OPNsense/Zapret') is None,
         'FOREIGN_OR_EXISTING_ZAPRET_CONFIG_REFUSE_OVERWRITE')
    return data, stat.S_IMODE(info.st_mode), info.st_uid, info.st_gid, root


def insert_test_model(root):
    opn = root.find('./OPNsense')
    if opn is None:
        opn = ET.SubElement(root, 'OPNsense')
    z = ET.SubElement(opn, 'Zapret')
    g = ET.SubElement(z, 'general')
    for k, v in [('enabled','1'), ('waninterface','lo0'), ('divertport','989'),
                 ('ports',str(PORT))]:
        ET.SubElement(g,k).text = v
    s = ET.SubElement(z, 'strategy')
    ET.SubElement(s, 'trafficargs').text = (
        '--filter-tcp=' + str(PORT) + '\n--filter-l7=tls\n'
        '--lua-desync=pktmod:ip_ttl=23')
    ET.SubElement(s, 'extraargs').text = ''
    h = ET.SubElement(z, 'hostlist')
    ET.SubElement(h, 'mode').text = 'all'
    return root


def write_config(data, mode, target=CONFIG, owner=None):
    fd, name = tempfile.mkstemp(prefix='stage0-config-', dir=str(target.parent))
    try:
        with os.fdopen(fd, 'wb') as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(name, mode)
        if owner is not None:
            os.chown(name, owner[0], owner[1])
        os.replace(name, target)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def fresh_owned_paths():
    for p in (ENGINE, RUNTIME / 'runtime-v2', PID,
              Path('/var/run/zapret2-supervisor-daemon.pid'),
              Path('/var/run/zapret2-supervisor-monitor.pid')):
        need(not p.exists() and not p.is_symlink(),
             'PREEXISTING_RUNTIME_OR_FOREIGN_PATH:' + str(p))


def original_generated():
    info = GENERATED.lstat()
    need(stat.S_ISREG(info.st_mode) and not GENERATED.is_symlink() and
         info.st_nlink == 1,
         'ORIGINAL_GENERATED_CONFIG_NOT_OWNED_REGULAR')
    data = GENERATED.read_bytes()
    need(data.startswith(b'# Auto-generated by OPNsense os-zapret2 plugin'),
         'ORIGINAL_GENERATED_CONFIG_PROVENANCE_UNKNOWN')
    return data, stat.S_IMODE(info.st_mode), (info.st_uid, info.st_gid)


def original_template_hostlists():
    entries = (RUNTIME / 'hostlist.txt', RUNTIME / 'hostlist-exclude.txt')
    saved = {}
    for path in entries:
        info = path.lstat()
        need(stat.S_ISREG(info.st_mode) and not path.is_symlink() and
             info.st_nlink == 1, 'ORIGINAL_TEMPLATE_HOSTLIST_NOT_REGULAR')
        data = path.read_bytes()
        need(not data.strip(), 'ORIGINAL_TEMPLATE_HOSTLIST_IS_NONEMPTY_REFUSE_OVERWRITE')
        saved[path] = (data, stat.S_IMODE(info.st_mode), (info.st_uid,info.st_gid))
    return saved


def stage_engine(upstream):
    existing = (sorted(p.name + (':symlink' if p.is_symlink() else
                     ':dir' if p.is_dir() else ':file')
                     for p in RUNTIME.iterdir())
                if RUNTIME.is_dir() and not RUNTIME.is_symlink() else [])
    need(not RUNTIME.is_symlink() and RUNTIME.is_dir() and
         {p.name for p in RUNTIME.iterdir()} ==
         {'zapret.conf', 'hostlist.txt', 'hostlist-exclude.txt'},
         'GLOBAL_RUNTIME_HAS_UNQUALIFIED_PREEXISTING_CONTENT:' + repr(existing))
    engine = upstream / 'binaries/my/dvtws2'
    need(engine.is_file() and not engine.is_symlink() and os.access(engine, os.X_OK),
         'PINNED_ENGINE_NOT_BUILT')
    for rel in ['binaries/my/dvtws2','lua/zapret-lib.lua',
                'lua/zapret-antidpi.lua', 'lua/zapret-auto.lua']:
        old = upstream / rel
        need(old.is_file() and not old.is_symlink(), 'MISSING_UPSTREAM_RESOURCE:' + rel)
        new = RUNTIME / rel
        new.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
        new.parent.chmod(0o755)
        shutil.copyfile(old, new)
        new.chmod(0o755 if rel.endswith('/dvtws2') else 0o644)
    # The original backend blob resolver checks this exact upstream
    # directory even when the one test strategy has no external blob.
    # Ship authentic pinned source resources, never a fabricated fixture.
    fake = upstream / 'files/fake'
    need(fake.is_dir() and not fake.is_symlink(),
         'GENUINE_UPSTREAM_FAKE_BLOB_DIRECTORY_MISSING')
    target = RUNTIME / 'files/fake'
    need(not target.exists() and not target.is_symlink(),
         'PREEXISTING_FAKE_BLOB_DIRECTORY_REFUSED')
    need(all(x.is_file() and not x.is_symlink() for x in fake.iterdir()),
         'NONREGULAR_UPSTREAM_FAKE_BLOB_INPUT')
    shutil.copytree(fake, target, symlinks=False)
    for item in (RUNTIME / 'files', target):
        item.chmod(0o755)
    for item in target.iterdir():
        item.chmod(0o644)
    need(target.is_dir() and len(list(target.iterdir())) == len(list(fake.iterdir())),
         'UPSTREAM_BLOB_COPY_MISMATCH')
    return hashlib.sha256(ENGINE.read_bytes()).hexdigest()


def plugin_rules():
    listing = command('/sbin/ipfw', '-q', 'list')
    need(listing.returncode == 0, 'IPFW_LIST_UNAVAILABLE')
    return [l for l in listing.stdout.splitlines() if l.startswith('190')]


def bounded_running(service, expected_bin):
    rc, out, err = status(service,'start')
    stage = Path('/var/run/zapret2-execution.status')
    stage_tail = (stage.read_text(errors='replace')[-850:] if
                  stage.is_file() and not stage.is_symlink() else 'NO_STAGE')
    dirs = [Path('/usr/local'), Path('/usr/local/etc'), RUNTIME,
            RUNTIME / 'lua', RUNTIME / 'lua/zapret-lib.lua']
    ownership = [(str(path), oct(stat.S_IMODE(path.lstat().st_mode)),
                  path.lstat().st_uid, path.lstat().st_gid)
                 for path in dirs if path.exists()]
    need(rc == 0, 'REAL_START_FAILED:paths=' + repr(ownership) +
         ':rc=' + str(rc) +
         ':stdout_head=' + repr(out[:220]) +
         ':stdout_tail=' + repr(out[-250:]) +
         ':stderr_head=' + repr(err[:320]) +
         ':stderr_tail=' + repr(err[-300:]) +
         ':stage=' + repr(stage_tail))
    rc, out, err = status(service,'status')
    need(rc == 0 and 'zapret is running' in out,
         'ORIGINAL_SERVICE_NOT_RUNNING:' + str(rc) + ':' + (out+' '+err)[-240:])
    need(PID.is_file() and not PID.is_symlink(), 'ENGINE_PIDFILE_ABSENT_OR_SYMLINK')
    number = PID.read_text().strip()
    need(number.isdecimal() and int(number) > 1, 'ENGINE_PIDFILE_INVALID')
    commandline = command('/bin/ps','-p',number,'-o','command=')
    need(commandline.returncode == 0 and
         commandline.stdout.split(' ')[0] == str(ENGINE),
         'RUNNING_PROCESS_EXECUTABLE_NOT_OWNED:' + commandline.stdout[:170])
    need(hashlib.sha256(ENGINE.read_bytes()).hexdigest() == expected_bin,
         'RUNNING_ENGINE_BINARY_CHANGED')
    rules = plugin_rules()
    need(any(l.startswith(str(RULE)+' ') and 'divert 989' in l and '65431' in l
             and 'lo0' in l for l in rules),
         'OWNED_LOOPBACK_ONLY_DIVERT_NOT_OBSERVED:' + repr(rules))
    return number


def residual_processes(census, tokens):
    """Exact disallowed-command tokens; no weakening of pre-pkg owner guard."""
    return [line.strip() for line in census.splitlines()
            if any(token in line for token in tokens)]


OLD_SUPERVISOR_PARENT = re.compile(
    r'^\s*(\d+)\s+1\s+daemon: /usr/local/opnsense/scripts/OPNsense/'
    r'Zapret/supervisor_loop\.sh\[(\d+)\] \(daemon\)\s*$')


def classify_post_stop_residuals(detailed):
    """Known historical orphan is negative product evidence, never clean Stop."""
    if not detailed:
        return {'outcome': 'NO_OWNED_PROCESSES_AFTER_STOP', 'orphan_pid': None}
    need(len(detailed) == 1, 'POST_STOP_MULTIPLE_OR_FOREIGN_OWNERS:' + repr(detailed[:6]))
    match = OLD_SUPERVISOR_PARENT.fullmatch(detailed[0])
    need(match is not None, 'POST_STOP_UNRECOGNIZED_PROCESS:' + repr(detailed[0][:550]))
    need(match.group(1) != match.group(2),
         'POST_STOP_ORPHAN_PARENT_CHILD_ID_COLLISION')
    return {'outcome': 'HISTORICAL_STOP_LEFT_DAEMONIZED_SUPERVISOR_PARENT',
            'orphan_pid': int(match.group(1)), 'reported_child_pid': int(match.group(2))}


def stop_and_observe_kernel(service, inspector):
    rc, out, err = status(service,'stop')
    need(rc == 0, 'REAL_OLD_STOP_FAILED:' + str(rc) + ':' + (out+' '+err)[-280:])
    rc, out, err = status(service,'status')
    need(rc == 1 and out == 'zapret is not running',
         'SERVICE_NOT_STOPPED_AFTER_OLD_STOP:' + str(rc) + ':' + (out+' '+err)[-250:])
    need(not plugin_rules(), 'OLD_STOP_LEFT_PLUGIN_IPFW_RULES')
    need(not PID.exists(), 'OLD_STOP_LEFT_ENGINE_PIDFILE')
    # The production Stop does NOT own shared-kernel module lifecycle.
    # Confirm only the native built-in default allow remains; do not
    # forcibly unload ipfw or ipdivert as a false cold-state target.
    guard = module('stage0-opnsense-foreign-ipfw-admission.py')
    ipfw = command('/sbin/ipfw','-q','list')
    need(ipfw.returncode == 0 and guard.only_default(ipfw.stdout),
         'POST_STOP_FOREIGN_OR_REMAINING_IPFW_RULES')
    for loaded in ('ipfw', 'ipdivert'):
        probe = command('/sbin/kldstat','-q','-m',loaded)
        need(probe.returncode == 0,
             'POST_STOP_KERNEL_MODULE_IDENTITY_CHANGED:' + loaded)
    # A historical daemon -P supervisor parent may outlive the monitor.
    # Allow at most 3 seconds of read-only natural exit; no signals here.
    census = inspector.checked_process_census()
    matches = residual_processes(census, inspector.PROCESS_TOKENS)
    for _ in range(3):
        if not matches:
            break
        time.sleep(1)
        census = inspector.checked_process_census()
        matches = residual_processes(census, inspector.PROCESS_TOKENS)
    if not matches:
        inspector.check_process_census(census)
        return classify_post_stop_residuals([])
    # Invoke the original strict owner guard and require it to refuse.
    try:
        inspector.check_process_census(census)
    except inspector.Refusal as exc:
        need(str(exc) == 'POSSIBLE_ZAPRET_PROCESS_PRESENT',
             'POST_STOP_ORIGINAL_GUARD_UNEXPECTED_REFUSAL:' + str(exc))
    else:
        raise Refusal('POST_STOP_ORIGINAL_GUARD_ACCEPTED_RESIDUAL')
    pid_census = command('/bin/ps', '-ax', '-o', 'pid=', '-o', 'ppid=',
                         '-o', 'command=')
    need(pid_census.returncode == 0, 'POST_STOP_RESIDUAL_IDENTITY_UNAVAILABLE')
    detailed = residual_processes(pid_census.stdout, inspector.PROCESS_TOKENS)
    need(detailed, 'POST_STOP_RESIDUAL_VANISHED_DURING_IDENTITY_PROBE')
    # Historical parent leak is a NEGATIVE product witness, not proof of a
    # clean Stop nor authority to replace a package or kill the parent.
    return classify_post_stop_residuals(detailed)

def run(archive):
    qualify_guest()
    installer = module('stage0-opnsense-installed-predecessor.py')
    inspector = module('stage0-opnsense-prepkg-readonly.py')
    original = module('stage0-installed-predecessor-readonly.py')
    upstream = module('stage0-opnsense-upstream-engine-build.py')
    installer.install_and_verify(archive)
    hostname = original.run('hostname','-s').decode().strip()
    identity = original.run_guest(archive,hostname)
    need(inspector.snapshot(archive)['status']=='PASS_COLD_READ_ONLY_SNAPSHOT_ONLY',
         'REAL_OLD_NOT_INITIAL_COLD')
    fresh_owned_paths()
    snapshot, mode, uid, gid, xml = original_config()
    generated_old, generated_mode, generated_owner = original_generated()
    saved_hostlists = original_template_hostlists()
    runtime_info = RUNTIME.lstat()
    need(stat.S_ISDIR(runtime_info.st_mode) and not RUNTIME.is_symlink(),
         'NATIVE_RUNTIME_ROOT_NOT_REGULAR_DIRECTORY')
    runtime_initial_mode = stat.S_IMODE(runtime_info.st_mode)
    with tempfile.TemporaryDirectory(prefix='stage0-owned-real-start-') as td:
        folder=Path(td)
        upstream.build(folder)
        upstream_sha = upstream.PIN
        engine_sha = stage_engine(folder/'upstream')
        # Genuine upstream Setup makes this directory traversable by nobody;
        # the package-only template may have a restrictive original mode.
        # Only the disposable guest is changed, with exact mode restoration.
        RUNTIME.chmod(0o755)
        try:
            generated = ET.tostring(insert_test_model(xml), encoding='utf-8')
            write_config(generated,mode,owner=(uid,gid))
            reload = command('/usr/local/sbin/configctl', 'template', 'reload',
                             'OPNsense/Zapret')
            need(reload.returncode == 0 and reload.stdout.strip() == 'OK',
                 'NATIVE_TEMPLATE_GENERATION_REFUSED:' +
                 (reload.stdout+reload.stderr)[-250:])
            rendered = GENERATED.read_text()
            need('ZAPRET_ENABLED="1"' in rendered and 'WAN_IF="lo0"' in rendered and
                 '--filter-tcp='+str(PORT) in rendered,
                 'NATIVE_TEMPLATE_DID_NOT_RENDER_ISOLATED_TEST_MODEL')
            # The real historical service calls actual configctl template reload.
            # This is a fresh disposable VM, Config and generated runtime are
            # test-owned. Never mock the production template command.
            pid = bounded_running(original.SERVICE, engine_sha)
            stop_result = stop_and_observe_kernel(original.SERVICE, inspector)
        finally:
            # Source-only experiment: only restore Config if its exact
            # test-generated contents are still present; no generic Stop
            # of unknown owners or deletion of foreign files.
            if CONFIG.read_bytes()==generated:
                write_config(snapshot,mode,owner=(uid,gid))
            else:
                raise Refusal('CONFIG_CHANGED_DURING_TEST_REFUSE_OVERWRITE')
            # The generated Zapret file pre-existed from authentic package
            # installation. Restore only this verified test-owned rendered
            # file, never an unrelated or replaced pathname.
            if GENERATED.is_symlink() or not GENERATED.is_file() or not \
               GENERATED.read_bytes().startswith(b'# Auto-generated by OPNsense os-zapret2 plugin'):
                raise Refusal('GENERATED_CONFIG_FOREIGN_CHANGE_REFUSE_RESTORE')
            write_config(generated_old,generated_mode,GENERATED,generated_owner)
            for path, (before, saved_mode, owner) in saved_hostlists.items():
                if path.is_symlink() or not path.is_file() or path.read_bytes().strip():
                    raise Refusal('TEMPLATE_HOSTLIST_FOREIGN_CHANGE_REFUSE_RESTORE')
                write_config(before, saved_mode, path, owner)
            RUNTIME.chmod(runtime_initial_mode)
            need(stat.S_IMODE(RUNTIME.lstat().st_mode) == runtime_initial_mode,
                 'ORIGINAL_RUNTIME_DIRECTORY_MODE_NOT_RESTORED')
    need(identity == original.run_guest(archive,hostname),
         'ORIGINAL_INSTALLED_PKG_CHANGED_AFTER_RUNNING_EXPERIMENT')
    rc, out, err = status(original.SERVICE,'status')
    need(rc == 1 and out == 'zapret is not running',
         'FINAL_ORIGINAL_STOPPED_NOT_VERIFIED')
    need(not plugin_rules() and not PID.exists(),
         'FINAL_OWNED_RUNTIME_NOT_CLEAN')
    stop_clean = stop_result['outcome'] == 'NO_OWNED_PROCESSES_AFTER_STOP'
    outcome = ('PASS_GENUINE_OLD_STOP_CLEAN_WITH_KERNEL_MODULES_LOADED'
               if stop_clean else
               'PASS_REPRODUCED_OLD_STOP_SUPERVISOR_PARENT_LEAK')
    return {'schema':1,
            'status':outcome,
            'upstream_sha':upstream_sha,'built_engine_sha256':engine_sha,
            'real_original_start_status_stop':True,'real_running_pid_observed':pid,
            'real_loopback_owned_ipfw_rule_observed':True,
            'native_fd9_original_service':True,
            'original_pkg_unchanged':True,
            'original_cold_after_stop':False,
            'kernel_modules_remain_loaded':True,
            'no_owned_ipfw_rules_after_stop':True,
            'stop_kernel_observation':stop_result,
            'stop_all_processes_clean':stop_clean,
            'historical_supervisor_parent_leak_reproduced':not stop_clean,
            'native_pkg_replacement_safe_after_stop':False,
            'genuine_running_engine_tested':True,
            'actual_package_upgrade_tested':False,
            'full_lifecycle_acceptance_passed':False,'stage0_closed':False}


def main():
    if len(sys.argv)!=2:
        print('STAGE0_GENUINE_RUN=REFUSED:ARCHIVE_REQUIRED',file=sys.stderr)
        return 2
    try:
        print('STAGE0_GENUINE_RUN='+json.dumps(run(Path(sys.argv[1])),sort_keys=True))
        return 0
    except (Refusal, OSError, ValueError, TypeError, KeyError, ET.ParseError) as e:
        print('STAGE0_GENUINE_RUN=REFUSED:'+str(e),file=sys.stderr)
        return 2


if __name__=='__main__':
    sys.exit(main())
