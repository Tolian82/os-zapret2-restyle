#!/usr/bin/env python3
"""TZ6v5 S03b: genuine old-generator effective diff *evidence* (not a planner).

Reuses P2e OriginalSharedGeneration, whose shell calls the production
orchestrator_build_release, Python Voice/compiler and native source-map emitter.
Only original generated bytes and staged files are compared, never test-made
dvtws argv. No engine installation, FD9, IPFW, Config.xml or service changes.

Deliberate scope: document NO_CHANGE vs content-only argv-stable candidates vs
structural differences BEFORE implementing the future S08 pure diff planner.
An argv-stable change is NOT itself proof that Reload is safe.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import os
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
BUILDER = ROOT / "scripts/test-p2e-original-shared-build.py"
STRATEGY = (
    "--filter-tcp=443\n--filter-l7=tls\n<HOSTLIST:youtube>\n"
    "--lua-desync=fake\n--new\n"
    "--filter-tcp=80\n<HOSTLIST:user>\n--lua-desync=fake\n"
)
REORDERED = (
    "--filter-tcp=80\n<HOSTLIST:user>\n--lua-desync=fake\n--new\n"
    "--filter-tcp=443\n--filter-l7=tls\n<HOSTLIST:youtube>\n--lua-desync=fake\n"
)
ALTERED_DPI = STRATEGY.replace("--lua-desync=fake", "--lua-desync=multisplit", 1)

EXPECTED = {
    "same_input": "NO_CHANGE_SOURCE_EQUAL",
    "youtube_contents": "CONTENT_ONLY_CANDIDATE_UNPROVEN_RELOAD",
    "user_contents": "CONTENT_ONLY_CANDIDATE_UNPROVEN_RELOAD",
    "exclude_contents": "CONTENT_ONLY_CANDIDATE_UNPROVEN_RELOAD",
    "profile_order": "STRUCTURAL_DIFFERENCE",
    "dpi_args": "STRUCTURAL_DIFFERENCE",
    "voice_enabled": "STRUCTURAL_DIFFERENCE",
    "divert_port": "STRUCTURAL_DIFFERENCE",
    "target_mode": "SEMANTIC_MODE_CHANGE_EVEN_IF_ARGV_EQUAL",
    "exclude_presence": "STRUCTURAL_DIFFERENCE",
}


def digest(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def load_builder():
    spec = importlib.util.spec_from_file_location("s03b_original_producer", BUILDER)
    if spec is None or spec.loader is None:
        raise AssertionError("REAL_P2E_GENERATOR_MISSING")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def produce(module, *, strategy=STRATEGY, voice_on=False, mode="auto",
            youtube_domains="youtube.com", user_domains="example.org",
            exclude_domains="", divert_port="19899") -> dict:
    fixture = module.OriginalSharedGeneration("runTest")
    fixture.setUp()
    try:
        mapped, args = fixture.build(
            strategy, voice_on=voice_on, mode=mode,
            youtube_domains=youtube_domains,
            user_domains=user_domains,
            exclude_domains=exclude_domains,
            divert_port=divert_port, rule_max="19099",
        )
        # Only random disposable root is normalized; retain actual argv
        # options, ordering, and canonical active reference paths.
        emitted = args.read_bytes()
        normalized = emitted.replace(str(fixture.root).encode(),
                                     b"{DISPOSABLE_ROOT}")
        managed = fixture.release / "managed"
        files = {}
        for name in (
            "hostlist-youtube.txt", "hostlist-user.txt",
            "hostlist-exclude.txt", "ipset-telegram.txt",
        ):
            file = managed / name
            if file.is_file() and not file.is_symlink():
                files[name] = digest(file.read_bytes())
        if mode == "auto":
            source = fixture.check_nonactivating(mapped, args)
            profiles = [
                [x.get("role"), x.get("status"),
                 x.get("selector"), x.get("hostlist"),
                 x.get("native_number")]
                for x in source["profiles"]
            ]
        else:
            # Original legacy builder does NOT emit source map in List/All.
            if mapped.exists():
                raise AssertionError("UNEXPECTED_ORIGINAL_SOURCE_MAP_FOR_NONAUTO")
            profiles = None
        if (fixture.release / "manifest.json").exists():
            raise AssertionError("PRE_V5_BUILDER_UNEXPECTEDLY_HAS_V5_MANIFEST")
        if not normalized.startswith(f"--port={divert_port}\n".encode()):
            raise AssertionError("REAL_ORIGINAL_DIVERT_VALUE_NOT_PROPAGATED")
        return {
            "args_hash": digest(normalized),
            "arg_bytes": normalized,  # transient, NEVER printed
            "managed": files,
            "profiles": profiles,
            "mode": mode,
        }
    finally:
        fixture.doCleanups()


def classify_evidence(before: dict, after: dict) -> str:
    same_argv = before["arg_bytes"] == after["arg_bytes"]
    same_managed = before["managed"] == after["managed"]
    if (same_argv and same_managed and before["mode"] == after["mode"]
            and before["profiles"] == after["profiles"]):
        return "NO_CHANGE_SOURCE_EQUAL"
    if before["mode"] != after["mode"]:
        return "SEMANTIC_MODE_CHANGE_EVEN_IF_ARGV_EQUAL"
    if not same_argv or before["profiles"] != after["profiles"]:
        return "STRUCTURAL_DIFFERENCE"
    if not same_managed:
        return "CONTENT_ONLY_CANDIDATE_UNPROVEN_RELOAD"
    raise AssertionError("UNCLASSIFIED_REAL_GENERATOR_CHANGE")


class RealOriginalDiffEvidence(unittest.TestCase):
    """One suite; every output built by original shell path in a separate dir."""

    def test_real_emitted_state_matrix(self):
        mod = load_builder()
        baseline = produce(mod)
        modified = {
            "same_input": produce(mod),
            "youtube_contents": produce(
                mod, youtube_domains="youtube.com\nm.youtube.example.org"),
            "user_contents": produce(
                mod, user_domains="example.org\nuser.alt.example.org"),
            "exclude_contents": produce(
                mod, exclude_domains="ads.one.example.org\n"),
            "profile_order": produce(mod, strategy=REORDERED),
            "dpi_args": produce(mod, strategy=ALTERED_DPI),
            "voice_enabled": produce(mod, voice_on=True),
            "divert_port": produce(mod, divert_port="19900"),
            "target_mode": produce(mod, mode="list"),
            "exclude_presence": produce(
                mod, exclude_domains="ads.one.example.org\n"),
        }
        # For content edits of an ALREADY linked active Exclude reference,
        # compare nonempty -> different nonempty. Empty -> nonempty introduces
        # a new --hostlist-exclude= argv flag and is structural.
        nonempty_old = produce(mod, exclude_domains="ads.one.example.org\n")
        nonempty_new = produce(mod, exclude_domains="ads.two.example.org\n")
        got = {
            name: classify_evidence(
                nonempty_old if name == "exclude_contents" else baseline,
                nonempty_new if name == "exclude_contents" else candidate)
            for name, candidate in modified.items()
        }
        self.assertEqual(got, EXPECTED)
        # Nonempty list contents must actually differ in staged original
        # storage, not merely in JSON test input.
        self.assertNotEqual(
            baseline["managed"]["hostlist-youtube.txt"],
            modified["youtube_contents"]["managed"]["hostlist-youtube.txt"])
        self.assertNotEqual(
            baseline["managed"]["hostlist-user.txt"],
            modified["user_contents"]["managed"]["hostlist-user.txt"])
        self.assertNotEqual(
            nonempty_old["managed"]["hostlist-exclude.txt"],
            nonempty_new["managed"]["hostlist-exclude.txt"])
        for name in ("youtube_contents", "user_contents", "exclude_contents"):
            left = nonempty_old if name == "exclude_contents" else baseline
            right = nonempty_new if name == "exclude_contents" else modified[name]
            self.assertEqual(left["arg_bytes"], right["arg_bytes"],
                             "Content-only case changed actual native argv: " + name)
        # Observe real source-map first-match identities, not guessed index.
        self.assertEqual(
            [row[3] for row in baseline["profiles"]
             if row[1] == "known-hostlist"],
            ["youtube", "user"])
        # Demonstrate critical blind spot: original argv can be identical,
        # but changing Auto->List is a semantic structural change.
        self.assertEqual(baseline["arg_bytes"],
                         modified["target_mode"]["arg_bytes"])
        self.assertNotEqual(baseline["mode"], modified["target_mode"]["mode"])
        # Report only hashes/categories, never raw domains or args.
        witness = {
            "marker": "TZ6V5_S03B_REAL_ORIGINAL_EFFECTIVE_DIFF_BASELINE",
            "source": "original orchestrator_build_release in P2e fixture",
            "scope": "SOURCE_ONLY_NO_RUNTIME_APPLY_NO_RELOAD_NATIVE_CLAIM",
            "baseline_argv_sha256": baseline["args_hash"],
            "case_count": len(got),
            "observations": got,
            "no_future_planner_implemented": True,
        }
        print(witness["marker"] + "=" + json.dumps(witness, sort_keys=True))
        print("S03B_ACTUAL_OLD_GENERATOR_BASELINE=PASS")
        print("S03B_RELOAD_SAFE_NATIVE_NOT_CLAIMED=1")


if __name__ == "__main__":
    unittest.main(verbosity=2)
